type Join<K, P> = K extends string
  ? P extends string
    ? `${K}.${P}`
    : never
  : never;

export type TranslationKey<T = Messages> = T extends string
  ? never
  : {
      [K in keyof T]: T[K] extends string ? K & string : Join<K & string, TranslationKey<T[K]>>;
    }[keyof T];
